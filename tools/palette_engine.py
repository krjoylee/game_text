def get_base_color_ansi(base_idx):
    """3대 기본 베이스 색상의 ANSI 코드"""
    ansi_code = BASE_3_COLORS[base_idx][1]
    return ansi_code

def get_synthesized_pixel(color_target_id, px, py):
    """
    16가지 목표 색상 ID를 3x3 딕셔너리에 통과시켜
    (px, py) 좌표의 3대 베이스 기본 색상(0, 1, 2, 3)을 즉시 산출
    """
    matrix_9 = COLOR_DICT_9.get(color_target_id, COLOR_DICT_9[0])
    base_idx = matrix_9[py % 3][px % 3]
    return base_idx

def render_half_block_row(top_bases, bot_bases):
    """
    상단 베이스 색상 행과 하단 베이스 색상 행을 하프블록(▀)으로 결합
    """
    line_parts = []
    cur_fg = -1
    cur_bg = -1
    for t, b in zip(top_bases, bot_bases):
        if t != cur_fg or b != cur_bg:
            fg_code = BASE_3_COLORS[t][1]
            bg_code = BASE_3_COLORS[b][1]
            line_parts.append(f"\x1b[38;5;{fg_code};48;5;{bg_code}m")
            cur_fg = t
            cur_bg = b
        line_parts.append("▀")
    line_parts.append("\x1b[0m")
    return "".join(line_parts)

def calculate_8bit_packed_size(color_id_matrix):
    """
    8비트 팩킹 용량 계산:
    - 목표 색상 16개(4비트)는 1바이트(8비트)에 2칸씩 팩킹됨!
    - 3x3 딕셔너리 매핑을 통해 실제 화소는 9배로 뻥튀기되지만,
      저장 데이터는 1바이트당 2개 블록만 저장하므로 용량이 절반으로 수직 다이어트!
    """
    h = len(color_id_matrix)
    w = len(color_id_matrix[0])
    total_cells = h * w
    packed_bytes = (total_cells + 1) // 2 # 4비트 팩킹
    return packed_bytes
